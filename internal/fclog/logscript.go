package fclog

// @log の Mesen 2 用スクリプト (<rom>.fclog.lua)。Mesen 2 の Lua API (emu.addMemoryCallback の exec、emu.read、
// emu.getState、emu.convertAddress、emu.log) だけを使う。地点の PC に来たら、同じ CPU アドレスに別のバンクが載ることが
// あるので PRG ROM 上の位置まで照合してから、値を副作用の無い読み出しで読んで整形する。書式の規則は formatLogValue と同じ。

import (
	"fmt"
	"sort"
	"strings"
)

func luaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range []byte(s) {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteByte(r)
		case r < 0x20 || r >= 0x7f:
			fmt.Fprintf(&b, "\\%03d", r)
		default:
			b.WriteByte(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func luaValue(v LogFileValue) string {
	s := fmt.Sprintf("{ loc = %s, addr = %d, reg = %s, value = %d", luaString(v.Loc), v.Addr, luaString(v.Reg), v.Value)
	if len(v.Bytes) > 0 {
		s += ", bytes = {"
		for _, b := range v.Bytes {
			s += " " + luaValue(b) + ","
		}
		s += " }"
	}
	return s + " }"
}

// mesenLogScript は LogFile を埋め込んだ Lua を返す。
func mesenLogScript(lf *LogFile) string {
	var b strings.Builder
	b.WriteString(`-- fc @log for Mesen 2 (generated by fcc build -g; do not edit)
-- Load this script in Mesen (Debug > Script Window) with the ROM built at the same time.
local points = {
`)
	for _, p := range lf.Points {
		fmt.Fprintf(&b, "  { id = %d, file = %s, line = %d,\n    parts = {", p.ID, luaString(p.File), p.Line)
		for _, part := range p.Parts {
			if part.Arg < 0 {
				fmt.Fprintf(&b, " { text = %s },", luaString(part.Text))
			} else {
				fmt.Fprintf(&b, " { arg = %d, verb = %s, width = %d, zero = %t, prec = %d },", part.Arg+1, luaString(part.Verb), part.Width, part.Zero, part.Prec)
			}
		}
		b.WriteString(" },\n    args = {")
		for _, a := range p.Args {
			fmt.Fprintf(&b, " { kind = %s, size = %d, signed = %t, frac = %d", luaString(a.Kind), a.Size, a.Signed, a.Frac)
			if len(a.Enum) > 0 {
				keys := make([]int, 0, len(a.Enum))
				for k := range a.Enum {
					keys = append(keys, k)
				}
				sort.Ints(keys)
				b.WriteString(", enum = {")
				for _, k := range keys {
					fmt.Fprintf(&b, " [%d] = %s,", k, luaString(a.Enum[k]))
				}
				b.WriteString(" }")
			}
			b.WriteString(" },")
		}
		b.WriteString(" },\n    sites = {\n")
		for _, s := range p.Sites {
			prevs := "nil"
			if s.Prevs != nil {
				prevs = "{"
				for _, p := range s.Prevs {
					prevs += fmt.Sprintf(" %d,", p)
				}
				prevs += " }"
			}
			fmt.Fprintf(&b, "      { seq = %d, pc = %d, prg = %d, prevs = %s, values = {", s.Seq, s.PC, s.Prg, prevs)
			for _, v := range s.Values {
				b.WriteString(" " + luaValue(v) + ",")
			}
			b.WriteString(" } },\n")
		}
		b.WriteString("    } },\n")
	}
	b.WriteString(`}

local cpuMem = emu.memType.nesDebug or emu.memType.nesMemory
local prgRom = emu.memType.nesPrgRom

local function readValue(v, size, state)
  -- state(key) は CPU の状態 (emu.getState は重いので、レジスタ・スタックを読むときだけ取る)
  if v.loc == "const" then return v.value end
  if v.loc == "bytes" then
    local n = 0
    for i, b in ipairs(v.bytes) do
      local x = readValue(b, 1, state)
      if x == nil then return nil end
      n = n | ((x & 0xff) << (8 * (i - 1)))
    end
    return n
  end
  if v.loc == "reg" then return state("cpu." .. v.reg) end
  if v.loc == "mem" or v.loc == "stack" then
    local addr = v.addr
    if v.loc == "stack" then addr = (addr + state("cpu.x")) & 0xff end
    local n = 0
    for i = 0, size - 1 do
      n = n | (emu.read((addr + i) & 0xffff, cpuMem, false) << (8 * i))
    end
    return n
  end
  return nil
end

local function toBase(v, base, upper)
  if v == 0 then return "0" end
  local digits = upper and "0123456789ABCDEF" or "0123456789abcdef"
  local s = ""
  while v > 0 do
    local d = v % base
    s = string.sub(digits, d + 1, d + 1) .. s
    v = v // base
  end
  return s
end

-- 固定小数 (中身 sv、小数のビット数 frac) の 10 進 (ir.FormatFixed と同じ: 桁の指定が無ければ正確な値、prec は桁 + 1 で四捨五入)
local function fixedText(sv, frac, prec)
  local neg = sv < 0
  local mag = neg and -sv or sv
  local one = 1 << frac
  local ip = mag >> frac
  local f = mag & (one - 1)
  local digits = {}
  local function digit()
    f = f * 10
    digits[#digits + 1] = f >> frac
    f = f & (one - 1)
  end
  if prec == 0 then
    while f ~= 0 do digit() end
  else
    for _ = 1, prec - 1 do digit() end
    if f * 2 >= one then
      local i = #digits
      while i >= 1 and digits[i] == 9 do digits[i] = 0; i = i - 1 end
      if i >= 1 then digits[i] = digits[i] + 1 else ip = ip + 1 end
    end
  end
  local s = tostring(ip)
  if #digits > 0 then
    s = s .. "."
    for _, d in ipairs(digits) do s = s .. tostring(d) end
  end
  if neg then s = "-" .. s end
  return s
end

-- 浮動小数 (ビット v、大きさ size) の 10 進 (ir.FormatFloat に近い形。string.format を使うので、ちょうど中間の値の丸めが違うことがある)
local function floatText(v, size, prec)
  local x
  if size == 2 then
    local e = (v >> 10) & 31
    local m = v & 0x3ff
    local s = ((v & 0x8000) ~= 0) and -1 or 1
    if e == 31 then
      if m ~= 0 then return "nan" end
      return (s < 0) and "-inf" or "inf"
    end
    if e == 0 then x = s * m * 2.0^-24 else x = s * (1024 + m) * 2.0^(e - 25) end
    if v == 0x8000 then x = -0.0 end
  else
    x = string.unpack("<f", string.pack("<I4", v))
  end
  if x ~= x then return "nan" end
  if x == math.huge then return "inf" end
  if x == -math.huge then return "-inf" end
  local a = math.abs(x)
  if prec > 0 then
    if a < 1e9 then return string.format("%." .. (prec - 1) .. "f", x) end
    return string.format("%." .. (prec - 1) .. "e", x)
  end
  if a == 0 then return (1 / x < 0) and "-0" or "0" end
  local e = string.format("%.6e", x)
  local k = tonumber(string.match(e, "e([-+]%d+)$"))
  local function trim(s) return (string.gsub(string.gsub(s, "0+$", ""), "%.$", "")) end
  if k >= -4 and k <= 8 then return trim(string.format("%.6f", x)) end
  local mant, ex = string.match(e, "^(.-)e(.*)$")
  return trim(mant) .. "e" .. ex
end

local function formatValue(a, part, v)
  local bits = 8 * a.size
  v = v & ((1 << bits) - 1)
  local sv = v
  if a.signed and v >= (1 << (bits - 1)) then sv = v - (1 << bits) end
  local s
  if part.verb == "x" then s = toBase(v, 16, false)
  elseif part.verb == "X" then s = toBase(v, 16, true)
  elseif part.verb == "b" then s = toBase(v, 2, false)
  elseif part.verb == "c" then s = string.char(v)
  elseif a.kind == "fixed" and (part.verb == "d" or part.verb == "") then s = fixedText(sv, a.frac, part.prec)
  elseif a.kind == "float" and (part.verb == "d" or part.verb == "") then s = floatText(v, a.size, part.prec)
  elseif part.verb == "d" then s = tostring(sv)
  elseif a.kind == "bool" then s = (v ~= 0) and "true" or "false"
  elseif a.kind == "enum" then s = (a.enum and a.enum[sv]) or tostring(sv)
  elseif a.kind == "ptr" then s = string.format("$%04X", v)
  else s = tostring(sv) end
  if part.width > #s then
    if part.zero and string.sub(s, 1, 1) == "-" then
      s = "-" .. string.rep("0", part.width - #s) .. string.sub(s, 2)
    else
      s = string.rep(part.zero and "0" or " ", part.width - #s) .. s
    end
  end
  return s
end

local function show(p, site)
  local st = nil
  local function state(key)
    st = st or emu.getState()
    return st[key]
  end
  local out = {}
  for _, part in ipairs(p.parts) do
    if part.text then
      out[#out + 1] = part.text
    else
      local v = readValue(site.values[part.arg], p.args[part.arg].size, state)
      out[#out + 1] = v and formatValue(p.args[part.arg], part, v) or "?"
    end
  end
  emu.log(table.concat(out))
end

-- 同じ PC の地点をまとめてフックする (PRG ROM 上の位置で、今載っているバンクの地点だけ出す。順番は seq = ソースの順)
local byPc = {}
for _, p in ipairs(points) do
  for _, site in ipairs(p.sites) do
    byPc[site.pc] = byPc[site.pc] or {}
    table.insert(byPc[site.pc], { p = p, site = site })
  end
end
for _, list in pairs(byPc) do
  table.sort(list, function(x, y) return x.site.seq < y.site.seq end)
end
-- 合流点の地点 (prevs がある) は、この地点の経路の直前の命令 (prevs) を実行したときに準備し、地点に来たら出して準備を
-- 解く (ループの先頭に付いた @log を後ろからの辺で来た周では出さない、何も出さない else の地点を then の後で出さない)。
-- 直前の命令が条件分岐なら、準備はその命令を実行したときのサイクル数で持ち、地点に来たときに 1 命令分 (8 サイクル以内)
-- の差のときだけ有効 (成立してほかへ行った後に別の経路で来たときに出さないように)。jsr (呼び出しの直後の地点) なら、
-- 呼び先の長さが分からないので、かわりに jsr のときのスタックポインタで持ち、戻って同じ値のときに有効 (再帰で同じ jsr を
-- 入れ子に通っても、戻るたびに合う)。ほかの命令 (jmp と、上から落ちてくる命令) の次は必ず地点なので印だけ。
-- emu.getState は 1 回 100 マイクロ秒ほどかかるので、要るとき (条件分岐・jsr、レジスタ・スタックの値) だけ呼ぶ
local condBranch = { [0x10] = true, [0x30] = true, [0x50] = true, [0x70] = true, [0x90] = true, [0xb0] = true, [0xd0] = true, [0xf0] = true }
local armed = {}
local armedCall = {}
local function cycles()
  local st = emu.getState()
  return st["cpu.cycleCount"]
end
local prevs = {}
for _, p in ipairs(points) do
  for _, site in ipairs(p.sites) do
    if site.prevs then
      for _, pc in ipairs(site.prevs) do
        prevs[pc] = prevs[pc] or {}
        table.insert(prevs[pc], site)
      end
    end
  end
end
for pc, sites in pairs(prevs) do
  emu.addMemoryCallback(function(address)
    local op = emu.read(address, cpuMem, false)
    if op == 0x20 then
      local sp = emu.getState()["cpu.sp"]
      for _, site in ipairs(sites) do
        armedCall[site] = armedCall[site] or {}
        armedCall[site][sp] = true
      end
      return
    end
    local c = true
    if condBranch[op] then c = cycles() or true end
    for _, site in ipairs(sites) do armed[site] = c end
  end, emu.callbackType.exec, pc, pc)
end
for pc, list in pairs(byPc) do
  emu.addMemoryCallback(function(address)
    local abs = nil
    for _, e in ipairs(list) do
      local ok = true
      if e.site.prevs then
        local a = armed[e.site]
        ok = a == true or (type(a) == "number" and (cycles() or a) - a <= 8)
        armed[e.site] = nil
        local calls = armedCall[e.site]
        if calls and next(calls) ~= nil then
          local sp = emu.getState()["cpu.sp"]
          if calls[sp] then
            ok = true
            calls[sp] = nil
          end
        end
      end
      if ok and e.site.prg >= 0 then
        abs = abs or emu.convertAddress(address, emu.memType.nesMemory)
        ok = abs ~= nil and abs.memType == prgRom and abs.address == e.site.prg
      end
      if ok then show(e.p, e.site) end
    end
  end, emu.callbackType.exec, pc, pc)
end
emu.log("fc @log: " .. #points .. " log points")
`)
	return b.String()
}
